DMA(Direct Memory Access)直接内存访问，可以大大减轻CPU工作量。
01.为什么要有DMA？
    CPU根据代码内容执行指令，这些众多指令中，有的用于计算、有的用于控制程序、有的用于转移数据等。其中转移数据的指令，尤其是转移大量数据，会占用大量CPU。
    如果是把外设A的数据，传给外设B，这种情况其实不需要CPU一直参与，只需在A、B之间创建个通道，让它们自己传输即可。
    这就是DMA设计的目的，减少大量数据转移指令消耗CPU，DMA专注数据转移，CPU专注计算、控制。
02.DMA的搬运模式有哪些？
    001.按数据流向来看： 
                      🟢外设 -> 内存 : UART/USART 接收数据到缓冲区； ADC 采样数据存入数组； SPI/I2C 从设备读取数据等
                                       配置要点：
                                                Direction = Peripheral to Memory
                                                外设地址不递增（Periph Inc = Disable，因为外设寄存器地址固定，比如 USART_DR/ADC_DR）
                                                内存地址递增（Memory Inc = Enable，数据依次存入数组）
                      🟢内存 -> 外设 ：UART/USART 发送缓冲区数据； SPI/I2C 向设备写入数据； TIM 触发 DAC 输出波形
                                       配置要点：
                                                Direction = Memory to Peripheral
                                                外设地址不递增（Periph Inc = Disable）
                                                内存地址递增（Memory Inc = Enable，依次读取数组数据）
                      🟢内存 -> 内存 ：快速拷贝大数组； Flash 数据批量搬运到 SRAM； 多缓冲区之间的数据交换
                                       配置要点：
                                                Direction = Memory to Memory
                                                外设 / 内存地址都可递增（Periph Inc = Enable，这里的 “外设” 实际是源内存地址）
                                                必须由软件触发传输（无外设请求信号）
   002.按传输行为来看：
                     🟢单次传输模式（Normal 模式）：
                                       工作逻辑：
                                                DMA 只会按配置的长度传输一次数据，传输完成后自动停止，通道进入空闲状态。
                                       典型场景：
                                                UART 单次发送固定长度数据； 一次性拷贝固定大小的内存数据
                                        优缺点：
                                                ✅ 优点：传输完成自动停止，不会覆盖数据，适合单次任务
                                                ❌ 缺点：无法持续传输，需要软件手动重启 DMA 才能开始下一次传输
                     🟢循环传输模式（Circular 模式）：
                                       工作逻辑：
                                                DMA 传输完成后，会自动重装传输计数器，重新从起始地址开始传输，无限循环，直到软件停止 DMA。
                                       典型场景：
                                                UART 持续接收数据（配合空闲中断实现不定长接收）
                                                ADC 连续采样（不断更新缓冲区数据）
                                                DAC 循环输出波形
                                         优缺点：
                                                ✅ 优点：无需软件干预，持续传输，不会丢数据
                                                ❌ 缺点：会不断覆盖缓冲区数据，需要配合「半传输 / 全传输中断」处理数据
03.DMA的底层结构是什么？
   001.通道（Channel / Stream）
        每个通道对应一个外设（如 UART1_RX、ADC、SPI2 等）
        通道之间独立，互不干扰
   002.地址寄存器组（最核心）
        CNDTR：传输计数器（还剩多少字节要搬）
        CPAR：外设地址寄存器（Peripheral Address）
        CMAR：内存地址寄存器（Memory Address）
   003.控制寄存器（CCR）
        决定怎么搬：
                  方向：外设→内存 / 内存→外设 / 内存→内存
                  模式：正常 / 循环
                  地址是否递增（外设 / 内存）
                  数据宽度（8/16/32bit）
                  优先级
                  中断使能
   004.仲裁器（Arbiter）
        多个通道同时请求时，决定谁先搬。
        优先级：软件设置 > 硬件通道号。

